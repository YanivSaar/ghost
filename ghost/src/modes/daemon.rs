//! Daemon mode: a persistent, headless ghost watcher.
//!
//! Unlike the interactive lenses, daemon mode has three personas:
//!
//! 1. **Install**: write a systemd unit (and config file) under
//!    `${GHOST_PREFIX}/etc/ghost/` + `${GHOST_PREFIX}/lib/systemd/system/`,
//!    enable + start it. All-or-nothing; idempotent.
//! 2. **Uninstall**: stop, disable, purge every file install wrote. Keeps
//!    `/var/log/ghost/` by default (user's data); `--purge` removes it.
//! 3. **Run**: the service itself. Attaches to a target spec, writes
//!    rotated `.ghost` segments under `/var/log/ghost/<slug>/`.
//!
//! All path prefixes are overridable via `GHOST_PREFIX` for sandbox
//! verification during release builds.
//!
//! There is **no network listener** — "remote standalone" here means the
//! daemon runs headless on whatever host you install it on. The user can
//! `scp` the session dir back and `ghost replay <segment>` locally.

use std::{
    path::{Path, PathBuf},
    sync::{atomic::AtomicBool, Arc},
    time::Duration,
};

use anyhow::{bail, Context, Result};

use crate::{
    session::{
        dir_writer::{RotationConfig, SessionDirWriter},
        format::SessionMeta,
    },
    supervisor,
};

/// Target spec for the daemon. Exactly one is honoured — install validates.
#[derive(Debug, Clone)]
pub enum DaemonTarget {
    Pid(u32),
    Tree(u32),
    Cgroup(String),
    Unit(String),
}

impl DaemonTarget {
    /// Short, filesystem-safe slug used for the session dir name and the
    /// systemd unit instance (`ghost@<slug>.service`).
    pub fn slug(&self) -> String {
        let raw = match self {
            DaemonTarget::Pid(p) => format!("pid-{p}"),
            DaemonTarget::Tree(p) => format!("tree-{p}"),
            DaemonTarget::Cgroup(c) => format!("cgroup-{c}"),
            DaemonTarget::Unit(u) => format!("unit-{u}"),
        };
        raw.chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                    c
                } else {
                    '_'
                }
            })
            .collect()
    }

    pub fn as_cli_args(&self) -> Vec<String> {
        match self {
            DaemonTarget::Pid(p) => vec!["--pid".into(), p.to_string()],
            DaemonTarget::Tree(p) => vec!["--tree".into(), p.to_string()],
            DaemonTarget::Cgroup(c) => vec!["--cgroup".into(), c.clone()],
            DaemonTarget::Unit(u) => vec!["--unit".into(), u.clone()],
        }
    }
}

/// Daemon configuration persisted at install time to `/etc/ghost/daemon.toml`
/// and parsed at service start. Keeps `ExecStart=` short.
#[derive(Debug, Clone)]
pub struct DaemonConfig {
    pub target: DaemonTarget,
    pub log_dir: PathBuf,
    pub rotation: RotationConfig,
}

impl DaemonConfig {
    pub fn to_toml(&self) -> String {
        let (kind, value) = match &self.target {
            DaemonTarget::Pid(p) => ("pid", p.to_string()),
            DaemonTarget::Tree(p) => ("tree", p.to_string()),
            DaemonTarget::Cgroup(c) => ("cgroup", format!("\"{}\"", c)),
            DaemonTarget::Unit(u) => ("unit", format!("\"{}\"", u)),
        };
        format!(
            "# ghost daemon configuration — generated by `ghost --install`.\n\
             # Edit then `systemctl restart ghost@<slug>.service` to apply.\n\
             \n\
             [target]\n\
             kind = \"{kind}\"\n\
             value = {value}\n\
             \n\
             [log]\n\
             dir = \"{dir}\"\n\
             \n\
             [rotation]\n\
             max_segment_bytes = {max_seg}\n\
             keep_segments = {keep}\n\
             max_age_secs = {age}\n",
            dir = self.log_dir.display(),
            max_seg = self.rotation.max_segment_bytes,
            keep = self.rotation.keep_segments,
            age = self.rotation.max_age.as_secs(),
        )
    }

    pub fn from_toml(s: &str) -> Result<Self> {
        let v: toml::Value = toml::from_str(s).context("parsing daemon.toml")?;
        let t = v.get("target").context("missing [target]")?;
        let kind = t
            .get("kind")
            .and_then(|x| x.as_str())
            .context("missing target.kind")?;
        let value = t.get("value").context("missing target.value")?;
        let target = match kind {
            "pid" => DaemonTarget::Pid(
                value
                    .as_integer()
                    .context("target.value must be integer for pid")? as u32,
            ),
            "tree" => DaemonTarget::Tree(
                value
                    .as_integer()
                    .context("target.value must be integer for tree")? as u32,
            ),
            "cgroup" => DaemonTarget::Cgroup(
                value
                    .as_str()
                    .context("target.value must be string for cgroup")?
                    .to_string(),
            ),
            "unit" => DaemonTarget::Unit(
                value
                    .as_str()
                    .context("target.value must be string for unit")?
                    .to_string(),
            ),
            other => bail!("unknown target.kind '{other}'"),
        };
        let log_dir: PathBuf = v
            .get("log")
            .and_then(|l| l.get("dir"))
            .and_then(|d| d.as_str())
            .unwrap_or("/var/log/ghost")
            .into();
        let r = v.get("rotation");
        let max_segment_bytes = r
            .and_then(|r| r.get("max_segment_bytes"))
            .and_then(|v| v.as_integer())
            .unwrap_or(100 * 1024 * 1024) as u64;
        let keep_segments = r
            .and_then(|r| r.get("keep_segments"))
            .and_then(|v| v.as_integer())
            .unwrap_or(10) as usize;
        let max_age_secs = r
            .and_then(|r| r.get("max_age_secs"))
            .and_then(|v| v.as_integer())
            .unwrap_or(24 * 60 * 60) as u64;
        Ok(Self {
            target,
            log_dir,
            rotation: RotationConfig {
                max_segment_bytes,
                keep_segments,
                max_age: Duration::from_secs(max_age_secs),
            },
        })
    }
}

/// Resolve path roots. `GHOST_PREFIX` overrides every root (used by the
/// install sandbox during release verification). An empty / unset prefix
/// means production: `/` is root.
#[derive(Debug, Clone)]
pub struct Layout {
    pub prefix: PathBuf,
    pub bin_dir: PathBuf,
    pub etc_dir: PathBuf,
    pub unit_dir: PathBuf,
    pub log_dir: PathBuf,
}

impl Layout {
    pub fn resolve() -> Self {
        let prefix: PathBuf = std::env::var_os("GHOST_PREFIX")
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from(""));
        let under = |p: &str| {
            if prefix.as_os_str().is_empty() {
                PathBuf::from(p)
            } else {
                prefix.join(p.trim_start_matches('/'))
            }
        };
        Self {
            prefix: prefix.clone(),
            bin_dir: under("/usr/local/bin"),
            etc_dir: under("/etc/ghost"),
            unit_dir: under("/etc/systemd/system"),
            log_dir: under("/var/log/ghost"),
        }
    }
}

/// Install-time options.
#[derive(Debug, Clone)]
pub struct InstallArgs {
    pub target: DaemonTarget,
    pub rotation: RotationConfig,
    pub dry_run: bool,
    /// If true, don't call `systemctl` — just lay down files. Useful on hosts
    /// without an active systemd (containers, WSL2) and in sandbox tests.
    pub no_systemctl: bool,
}

/// Unit template rendered at install time. Each daemon target gets a
/// dedicated service `ghost@<slug>.service`.
fn render_unit(bin: &Path, cfg_path: &Path, slug: &str) -> String {
    format!(
        "[Unit]\n\
         Description=ghost persistent watcher ({slug})\n\
         Documentation=https://github.com/YanivSaar/ghost\n\
         After=network.target\n\
         \n\
         [Service]\n\
         Type=simple\n\
         ExecStart={bin} daemon --config {cfg}\n\
         Restart=on-failure\n\
         RestartSec=5s\n\
         # ghost needs cap_bpf + cap_perfmon (and cap_sys_ptrace for cold mode);\n\
         # the installer applies these to the binary via setcap. We also\n\
         # grant them to the service so the launched process can inherit.\n\
         AmbientCapabilities=CAP_BPF CAP_PERFMON CAP_SYS_PTRACE\n\
         CapabilityBoundingSet=CAP_BPF CAP_PERFMON CAP_SYS_PTRACE\n\
         NoNewPrivileges=yes\n\
         ProtectSystem=strict\n\
         ProtectHome=yes\n\
         ReadWritePaths=/var/log/ghost\n\
         # Logs go through journal; our own session segments live under\n\
         # ReadWritePaths above.\n\
         StandardOutput=journal\n\
         StandardError=journal\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        bin = bin.display(),
        cfg = cfg_path.display(),
        slug = slug,
    )
}

/// Install a daemon unit for `args.target`. Returns the service name
/// (`ghost@<slug>.service`). Idempotent: writing the same unit over itself
/// is fine. Any failure before `systemctl enable --now` rolls back files
/// it wrote.
pub fn install(args: InstallArgs) -> Result<String> {
    let layout = Layout::resolve();
    let slug = args.target.slug();
    let service_name = format!("ghost@{slug}.service");
    let cfg_path = layout.etc_dir.join(format!("{slug}.toml"));
    let unit_path = layout.unit_dir.join(&service_name);
    let log_dir = layout.log_dir.join(&slug);
    let bin = layout.bin_dir.join("ghost");

    let cfg = DaemonConfig {
        target: args.target.clone(),
        log_dir: log_dir.clone(),
        rotation: args.rotation.clone(),
    };
    let unit = render_unit(&bin, &cfg_path, &slug);
    let cfg_toml = cfg.to_toml();

    if args.dry_run {
        println!("# ghost --install (dry run)");
        println!("# would write {}:", cfg_path.display());
        println!("{cfg_toml}");
        println!("# would write {}:", unit_path.display());
        println!("{unit}");
        println!("# would mkdir -p {}", log_dir.display());
        if !args.no_systemctl {
            println!(
                "# would run: systemctl daemon-reload && systemctl enable --now {service_name}"
            );
        }
        return Ok(service_name);
    }

    // Lay down the files, rolling back on error.
    let written: Vec<PathBuf> = {
        let mut w = Vec::new();
        // config
        if let Some(parent) = cfg_path.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("mkdir {}", parent.display()))?;
        }
        std::fs::write(&cfg_path, &cfg_toml)
            .with_context(|| format!("writing {}", cfg_path.display()))?;
        w.push(cfg_path.clone());
        // unit
        if let Some(parent) = unit_path.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("mkdir {}", parent.display()))?;
        }
        if let Err(e) = std::fs::write(&unit_path, &unit) {
            // rollback
            for p in &w {
                let _ = std::fs::remove_file(p);
            }
            return Err(anyhow::anyhow!("writing {}: {e}", unit_path.display()));
        }
        w.push(unit_path.clone());
        // log dir
        if let Err(e) = std::fs::create_dir_all(&log_dir) {
            for p in &w {
                let _ = std::fs::remove_file(p);
            }
            return Err(anyhow::anyhow!("mkdir {}: {e}", log_dir.display()));
        }
        w
    };

    eprintln!("ghost: wrote {}", cfg_path.display());
    eprintln!("ghost: wrote {}", unit_path.display());
    eprintln!("ghost: ensured {}", log_dir.display());
    let _ = written;

    if !args.no_systemctl {
        match std::process::Command::new("systemctl")
            .args(["daemon-reload"])
            .status()
        {
            Ok(s) if s.success() => {}
            Ok(s) => eprintln!("ghost: systemctl daemon-reload exited {s}"),
            Err(e) => {
                eprintln!("ghost: systemctl not available: {e} — unit file placed, not enabled")
            }
        }
        if let Err(e) = std::process::Command::new("systemctl")
            .args(["enable", "--now", &service_name])
            .status()
        {
            eprintln!("ghost: systemctl enable --now {service_name} failed: {e}");
        }
    }

    Ok(service_name)
}

/// Uninstall options.
#[derive(Debug, Clone)]
pub struct UninstallArgs {
    pub target: Option<DaemonTarget>,
    pub purge_logs: bool,
    pub dry_run: bool,
    pub no_systemctl: bool,
}

/// Remove daemon units. If `target` is None, every `ghost@*.service` + its
/// config under etc_dir is torn down. Logs under `/var/log/ghost/` stay by
/// default; `--purge` wipes them too.
pub fn uninstall(args: UninstallArgs) -> Result<Vec<String>> {
    let layout = Layout::resolve();
    let mut removed: Vec<String> = Vec::new();

    let slugs: Vec<String> = if let Some(t) = &args.target {
        vec![t.slug()]
    } else {
        // Discover installed units by scanning etc_dir.
        let mut v = Vec::new();
        if layout.etc_dir.exists() {
            for e in std::fs::read_dir(&layout.etc_dir)? {
                let e = e?;
                let name = e.file_name().to_string_lossy().to_string();
                if let Some(slug) = name.strip_suffix(".toml") {
                    v.push(slug.to_string());
                }
            }
        }
        v
    };

    for slug in &slugs {
        let service = format!("ghost@{slug}.service");
        let cfg = layout.etc_dir.join(format!("{slug}.toml"));
        let unit = layout.unit_dir.join(&service);
        let log = layout.log_dir.join(slug);

        if args.dry_run {
            println!("# ghost --uninstall (dry run) for {service}");
            println!("# would systemctl disable --now {service}");
            println!("# would rm {}", unit.display());
            println!("# would rm {}", cfg.display());
            if args.purge_logs {
                println!("# would rm -r {}", log.display());
            } else {
                println!("# would KEEP logs at {}", log.display());
            }
            continue;
        }

        if !args.no_systemctl {
            let _ = std::process::Command::new("systemctl")
                .args(["disable", "--now", &service])
                .status();
        }
        for p in [&unit, &cfg] {
            if p.exists() {
                if let Err(e) = std::fs::remove_file(p) {
                    eprintln!("ghost: could not remove {}: {e}", p.display());
                } else {
                    eprintln!("ghost: removed {}", p.display());
                }
            }
        }
        if args.purge_logs && log.exists() {
            if let Err(e) = std::fs::remove_dir_all(&log) {
                eprintln!("ghost: could not remove {}: {e}", log.display());
            } else {
                eprintln!("ghost: purged {}", log.display());
            }
        }
        removed.push(service);
    }

    if !args.dry_run && !args.no_systemctl {
        let _ = std::process::Command::new("systemctl")
            .args(["daemon-reload"])
            .status();
    }

    // If etc_dir is now empty, remove it so uninstall leaves no trace.
    if layout.etc_dir.exists() {
        if let Ok(mut it) = std::fs::read_dir(&layout.etc_dir) {
            if it.next().is_none() && !args.dry_run {
                let _ = std::fs::remove_dir(&layout.etc_dir);
            }
        }
    }

    Ok(removed)
}

/// Run the daemon: resolve target → open rotating session dir → start
/// supervisor pipeline → block until signalled or target exits.
pub fn run(cfg: DaemonConfig) -> Result<()> {
    let slug = cfg.target.slug();
    let session_dir = cfg.log_dir.clone();
    std::fs::create_dir_all(&session_dir)
        .with_context(|| format!("mkdir {}", session_dir.display()))?;

    // Resolve the attach pid + extras from the target spec.
    let (root_pid, extras, label, tracked_count, comm) = resolve_target(&cfg.target)?;

    let meta = SessionMeta::new(root_pid, comm.as_str(), "daemon");
    let dir_writer = Arc::new(SessionDirWriter::open(
        &session_dir,
        cfg.rotation.clone(),
        meta,
    )?);

    let sink = Some(dir_writer.sink());
    let stop = Arc::new(AtomicBool::new(false));

    // Rotation-maintenance thread.
    {
        let dw = Arc::clone(&dir_writer);
        let stop_m = Arc::clone(&stop);
        std::thread::spawn(move || {
            use std::sync::atomic::Ordering;
            while !stop_m.load(Ordering::Relaxed) {
                std::thread::sleep(Duration::from_secs(2));
                if let Err(e) = dw.tick() {
                    eprintln!("ghost daemon: rotation error: {e:#}");
                }
            }
            let _ = dw.flush_final();
        });
    }

    eprintln!(
        "ghost daemon: pid={root_pid} target={slug} session={} (seg<={}B keep={} age<={}s)",
        session_dir.display(),
        cfg.rotation.max_segment_bytes,
        cfg.rotation.keep_segments,
        cfg.rotation.max_age.as_secs()
    );

    supervisor::run_headless(root_pid, sink, extras, Some(label), tracked_count, stop)
}

fn resolve_target(t: &DaemonTarget) -> Result<(u32, Vec<u32>, String, usize, String)> {
    use crate::proc::stat::Stat;
    match t {
        DaemonTarget::Pid(p) => {
            let comm = Stat::read(*p)
                .map(|s| s.comm)
                .unwrap_or_else(|_| "?".into());
            Ok((*p, vec![], format!("pid({p})"), 1, comm))
        }
        DaemonTarget::Tree(p) => {
            use crate::target::tree::TreeTarget;
            let tree = TreeTarget::attach(*p)?;
            let extras: Vec<u32> = tree.members.iter().copied().filter(|m| *m != *p).collect();
            let comm = Stat::read(*p)
                .map(|s| s.comm)
                .unwrap_or_else(|_| "?".into());
            let label = format!("tree({p}) +{}", extras.len());
            let count = tree.members.len();
            Ok((*p, extras, label, count, comm))
        }
        DaemonTarget::Cgroup(path) | DaemonTarget::Unit(path) => {
            use crate::target::cgroup::CgroupTarget;
            let cg = CgroupTarget::attach(path)?;
            if cg.members.is_empty() {
                bail!("daemon: cgroup/unit {path} has no processes");
            }
            let root = cg.members[0];
            let extras: Vec<u32> = cg.members.iter().copied().filter(|m| *m != root).collect();
            let comm = Stat::read(root)
                .map(|s| s.comm)
                .unwrap_or_else(|_| "?".into());
            let total = cg.members.len();
            let label = format!("{} ({} procs)", cg.label, total);
            Ok((root, extras, label, total, comm))
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn slug_sanitises_special_chars() {
        let s = DaemonTarget::Cgroup("/sys/fs/cgroup/user.slice".into()).slug();
        assert!(!s.contains('/'));
        assert!(s.starts_with("cgroup-"));
    }

    #[test]
    fn config_toml_round_trips() {
        let cfg = DaemonConfig {
            target: DaemonTarget::Pid(123),
            log_dir: PathBuf::from("/var/log/ghost/pid-123"),
            rotation: RotationConfig {
                max_segment_bytes: 1024,
                keep_segments: 3,
                max_age: Duration::from_secs(60),
            },
        };
        let s = cfg.to_toml();
        let parsed = DaemonConfig::from_toml(&s).unwrap();
        match parsed.target {
            DaemonTarget::Pid(p) => assert_eq!(p, 123),
            _ => panic!("wrong target kind"),
        }
        assert_eq!(parsed.rotation.max_segment_bytes, 1024);
        assert_eq!(parsed.rotation.keep_segments, 3);
        assert_eq!(parsed.rotation.max_age.as_secs(), 60);
    }

    #[test]
    fn config_toml_cgroup_round_trips() {
        let cfg = DaemonConfig {
            target: DaemonTarget::Cgroup("my.slice".into()),
            log_dir: PathBuf::from("/tmp/ghost"),
            rotation: RotationConfig::default(),
        };
        let s = cfg.to_toml();
        let parsed = DaemonConfig::from_toml(&s).unwrap();
        match parsed.target {
            DaemonTarget::Cgroup(c) => assert_eq!(c, "my.slice"),
            _ => panic!("wrong target kind"),
        }
    }

    #[test]
    fn install_dry_run_writes_nothing() {
        let tmp = std::env::temp_dir().join(format!("ghost_install_dryrun_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);
        std::env::set_var("GHOST_PREFIX", &tmp);
        let args = InstallArgs {
            target: DaemonTarget::Pid(1),
            rotation: RotationConfig::default(),
            dry_run: true,
            no_systemctl: true,
        };
        let name = install(args).unwrap();
        assert_eq!(name, "ghost@pid-1.service");
        assert!(!tmp.exists(), "dry run should write nothing");
        std::env::remove_var("GHOST_PREFIX");
    }

    #[test]
    fn install_and_uninstall_cycle_leaves_no_files() {
        let tmp = std::env::temp_dir().join(format!("ghost_install_cycle_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);
        std::env::set_var("GHOST_PREFIX", &tmp);
        let args = InstallArgs {
            target: DaemonTarget::Pid(1),
            rotation: RotationConfig::default(),
            dry_run: false,
            no_systemctl: true,
        };
        install(args).unwrap();
        let layout = Layout::resolve();
        assert!(layout.etc_dir.join("pid-1.toml").exists());
        assert!(layout.unit_dir.join("ghost@pid-1.service").exists());
        assert!(layout.log_dir.join("pid-1").exists());

        let uargs = UninstallArgs {
            target: Some(DaemonTarget::Pid(1)),
            purge_logs: true,
            dry_run: false,
            no_systemctl: true,
        };
        uninstall(uargs).unwrap();
        assert!(!layout.etc_dir.join("pid-1.toml").exists());
        assert!(!layout.unit_dir.join("ghost@pid-1.service").exists());
        assert!(!layout.log_dir.join("pid-1").exists());
        std::env::remove_var("GHOST_PREFIX");
        let _ = std::fs::remove_dir_all(&tmp);
    }
}
